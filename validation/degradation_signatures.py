"""Gas-path degradation signatures: what a worn component does to EGT, fuel flow, N1 and N2.

Run with ``uv run python validation/degradation_signatures.py``. Writes
``docs/figures/degradation_signatures.png`` and ``validation/results/degradation_signatures.md``.

Each calibrated engine model is given the same hardware with one component group 1 point
(0.01) less polytropically efficient (``TurbofanEngine.with_components``), and flown at the
same thrust as the new engine: rated take-off thrust at sea-level static ISA, and 22 kN at
FL350, Mach 0.78. The changes are model predictions, not fleet data.
"""

from __future__ import annotations

import sys
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))

from propulsion import plotting as P  # noqa: E402
from propulsion.flight import FlightCondition  # noqa: E402
from propulsion.units import FT  # noqa: E402

from engines import ENGINES, SLS, calibrated_engine  # noqa: E402

RESULTS = Path(__file__).resolve().parent / "results"
FL350 = FlightCondition.at_altitude(35000 * FT, 0.78, geopotential=True)
FAULTS = (("fan", "e_f"), ("compressors", "e_c"), ("turbines", "e_t"))
CONDITIONS = (("take-off", SLS, None), ("cruise", FL350, 22e3))


def signatures(name):
    e = calibrated_engine(name)
    out = {}
    for cond, fc, F in CONDITIONS:
        F = F or e.design_point.thrust
        base = e.operate_at_thrust(fc, F)
        for fault, field in FAULTS:
            worn = e.with_components(
                e.components.with_(**{field: getattr(e.components, field) - 0.01})
            )
            p = worn.operate_at_thrust(fc, F)
            out[cond, fault] = {
                "dEGT45": p.Tt45 - base.Tt45,
                "dEGT5": p.Tt5 - base.Tt5,
                "dFF": 100 * (p.fuel_flow / base.fuel_flow - 1),
                "dN1": 100 * (p.N1 - base.N1),
                "dN2": 100 * (p.N2 - base.N2),
            }
    return out


def figure(sig):
    name = ENGINES[0]
    fig, axes = plt.subplots(1, 4, figsize=(13, 3.8))
    keys = [
        ("dEGT45", "Δ LPT inlet temp. [K]"),
        ("dFF", "Δ fuel flow [%]"),
        ("dN1", "Δ N1 [% pts]"),
        ("dN2", "Δ N2 [% pts]"),
    ]
    x = np.arange(len(FAULTS))
    for ax, (k, label) in zip(axes, keys, strict=True):
        for j, (cond, _, _) in enumerate(CONDITIONS):
            vals = [sig[name][cond, f][k] for f, _ in FAULTS]
            ax.bar(x + (j - 0.5) * 0.36, vals, width=0.34, color=P.SERIES[j], label=cond)
        ax.set_xticks(x, [f for f, _ in FAULTS])
        ax.axhline(0, color=P.REFERENCE, lw=0.8)
        ax.set_title(label, fontsize=10)
        ax.grid(axis="x", visible=False)
    axes[3].legend(loc="upper right")
    fig.suptitle(
        f"{name} model: 1-point efficiency loss, same thrust",
        x=0.02,
        ha="left",
        weight="bold",
        y=1.04,
    )
    return P.save(fig, "degradation_signatures.png")


def main():
    P.use_style()
    sig = {n: signatures(n) for n in ENGINES}
    lines = [
        "# Degradation signatures",
        "",
        "Generated by `validation/degradation_signatures.py`: one component group 0.01 less",
        "polytropically efficient, same thrust as the new engine (rated take-off thrust at",
        "sea-level static ISA; 22 kN at FL350, Mach 0.78). Model predictions.",
        "",
        "| engine | condition | worn component | Δ Tt45 [K] | Δ Tt5 [K] | Δ fuel flow [%] | "
        "Δ N1 [% pts] | Δ N2 [% pts] |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for n in ENGINES:
        for cond, _, _ in CONDITIONS:
            for fault, _ in FAULTS:
                s = sig[n][cond, fault]
                lines.append(
                    f"| {n} | {cond} | {fault} | {s['dEGT45']:+.1f} | {s['dEGT5']:+.1f} | "
                    f"{s['dFF']:+.2f} | {s['dN1']:+.2f} | {s['dN2']:+.2f} |"
                )
    RESULTS.mkdir(exist_ok=True)
    (RESULTS / "degradation_signatures.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    print(figure(sig))


if __name__ == "__main__":
    main()
